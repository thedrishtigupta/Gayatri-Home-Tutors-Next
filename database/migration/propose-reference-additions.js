// database/migration/propose-reference-additions.js
// Emits the vocabulary the legacy data needs but the v3 seed files lack.
// Review the output before running it — it is a proposal, not a migration step.
//
//   node database/migration/propose-reference-additions.js

const fs = require("fs");
const path = require("path");
const N = require("./normalize");

const rows = JSON.parse(fs.readFileSync(path.join(__dirname, "..", "tutors.json"), "utf8"));

/** Strings in the area field that are not places at all. */
const NOT_A_PLACE =
  /^(near|around|surrounding|nearby|any|all|every|north|south|east|west|central|home|online|camp|yes|no|etc|commerce|english|hindi|maths|math|science|sst|social|physics|chemistry|biology|accounts|economics|computer|tuition|student|class|classes)\b/i;

const areaCounts = new Map();
const subjectCounts = new Map();

for (const r of rows) {
  for (const a of N.parseAreas(r["Mention Areas"]).unmatched) {
    const k = N.clean(a).toLowerCase();
    if (k.length < 4 || NOT_A_PLACE.test(k)) continue;
    if (/^\d/.test(k)) continue;
    areaCounts.set(k, (areaCounts.get(k) || 0) + 1);
  }
  for (const s of N.parseSubjects(r["Mention Subjects"]).custom) {
    const k = N.clean(s).toLowerCase();
    if (k.length < 3) continue;
    subjectCounts.set(k, (subjectCounts.get(k) || 0) + 1);
  }
}

/**
 * Reviewed corrections, applied after counting so the tally still reflects
 * every spelling found in the source.
 *
 *   string  -> the canonical name to insert instead
 *   null    -> do not insert; it duplicates another entry
 *
 * Keep this in step with AREA_ALIASES in normalize.js, which maps the raw
 * spellings onto these names so the parser still matches them.
 */
const CANONICAL = {
  "mp enclave": "MP Enclave",
  "smarat enclave": "Samrat Enclave",
  "gujrawala town (part-1": "Gujranwala Town",
  yojnavihar: "Yojna Vihar",
  "chandar nagar": "Chander Nagar",
  rajdhani: null, // shortened "Rajdhani Enclave"
  chanderlok: null, // unspaced "Chander Lok"
};

const slugify = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

const titleCase = (s) =>
  s
    .replace(/[()]/g, "")
    .split(/\s+/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(" ")
    .trim();

const MIN_OCCURRENCES = 2;

const areas = [...areaCounts.entries()]
  .filter(([, c]) => c >= MIN_OCCURRENCES)
  .sort((a, b) => b[1] - a[1]);

const subjects = [...subjectCounts.entries()]
  .filter(([, c]) => c >= MIN_OCCURRENCES)
  .sort((a, b) => b[1] - a[1]);

const L = [];
L.push("-- database/migration/proposed-reference-additions.sql");
L.push("-- Vocabulary the legacy tutor data uses that the v3 seed files do not cover.");
L.push("-- GENERATED by propose-reference-additions.js — review every line before running.");
L.push(`-- Threshold: strings appearing in >= ${MIN_OCCURRENCES} legacy records.`);
L.push("");
L.push("START TRANSACTION;");
L.push("");
L.push("-- ── Delhi localities ─────────────────────────────────────────────");

const emitted = new Set();
let skipped = 0;

for (const [name, count] of areas) {
  const override = Object.prototype.hasOwnProperty.call(CANONICAL, name) ? CANONICAL[name] : undefined;

  if (override === null) {
    L.push(`-- skipped "${name}" (${count} tutors) — duplicate of another entry`);
    skipped += 1;
    continue;
  }

  const proper = override || titleCase(name);
  const slug = slugify(proper);

  if (emitted.has(slug)) {
    L.push(`-- skipped "${name}" (${count} tutors) — already inserted as "${proper}"`);
    skipped += 1;
    continue;
  }
  emitted.add(slug);

  const note = override ? `${count} tutors, spelt "${name}" in the export` : `${count} tutors`;
  L.push(
    `INSERT INTO locations (name, slug, location_type, parent_location_id) SELECT ${quote(proper)}, ${quote(
      slug
    )}, 'locality', id FROM locations WHERE slug = 'delhi-city' ON DUPLICATE KEY UPDATE is_active = TRUE;  -- ${note}`
  );
}

L.push("");
L.push("-- ── Subjects ─────────────────────────────────────────────────────");
L.push("-- Only add the ones that are genuinely school subjects; the rest should");
L.push("-- stay in tutor_custom_subjects for admin review.");
for (const [name, count] of subjects) {
  const proper = titleCase(name);
  L.push(`-- INSERT INTO subjects (name, slug) VALUES (${quote(proper)}, ${quote(slugify(proper))}) ON DUPLICATE KEY UPDATE is_active = TRUE;  -- ${count} tutors`);
}

L.push("");
L.push("COMMIT;");

function quote(s) {
  return `'${String(s).replace(/'/g, "''")}'`;
}

const outPath = path.join(__dirname, "proposed-reference-additions.sql");
fs.writeFileSync(outPath, L.join("\n"));

console.log(`localities proposed : ${areas.length}  (covering ${areas.reduce((a, [, c]) => a + c, 0)} legacy mentions)`);
console.log(`subjects proposed   : ${subjects.length}  (commented out — needs a human decision)`);
console.log(`\nwritten: ${path.relative(process.cwd(), outPath)}`);
